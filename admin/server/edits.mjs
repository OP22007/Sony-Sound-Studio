import { randomUUID } from 'node:crypto';
import { HttpError } from './security.mjs';

const platforms = ['windows', 'macos', 'linux'];
const text = (value, name, limit, required = true) => {
  if (typeof value !== 'string' || value.length > limit || (required && !value.trim()) || /[\u0000-\u0008\u000b\u000c\u000e-\u001f]/.test(value)) throw new HttpError(400, `${name} is required and must be at most ${limit} characters.`);
  return value.trim();
};
const date = value => /^\d{4}-\d{2}-\d{2}$/.test(value) && Number.isFinite(Date.parse(value)) && new Date(value).toISOString().slice(0,10) === value && value <= new Date().toISOString().slice(0,10);
export function effectiveModel(registry, model) {
  return {...model, platforms: Object.fromEntries(platforms.map(p => [p, {...registry.profiles?.[model.profile]?.platforms[p], ...model.platforms?.[p]}]))};
}
export function applyEdits(original, input, ownerId, now = new Date()) {
  if (!input || !Array.isArray(input.changes) || input.changes.length > 27) throw new HttpError(400, 'Choose up to 27 feature changes.');
  const registry = structuredClone(original);
  const model = registry.devices.find(m => m.id === input.modelId);
  if (!model) throw new HttpError(400, 'Unknown device.');
  const summary = text(input.summary, 'Model summary', 600);
  if (summary === model.summary && input.changes.length === 0) throw new HttpError(400, 'No changes to save.');
  model.summary = summary;
  model.reviewedOn = registry.reviewedOn = now.toISOString().slice(0,10);
  const seen = new Set();
  for (const change of input.changes) {
    const {platform, feature, status} = change;
    if (!platforms.includes(platform) || !Object.hasOwn(registry.features, feature) || !Object.hasOwn(registry.statuses, status)) throw new HttpError(400, 'Unknown platform, feature or status.');
    const key = `${platform}/${feature}`;
    if (seen.has(key)) throw new HttpError(400, 'Duplicate feature update.'); seen.add(key);
    const note = text(change.note, 'Public status note', 2000);
    const test = change.test || {};
    const fields = {};
    for (const [key, limit] of Object.entries({firmware:120,appVersion:120,testedOn:10,osVersion:160,requested:1000,readback:1000,observed:2000,steps:3000,reference:500})) {
      fields[key] = text(test[key] ?? '', key, limit, false);
    }
    if (fields.testedOn && !date(fields.testedOn)) throw new HttpError(400, 'Use a real test date that is not in the future.');
    if (fields.reference) {
      let url; try { url = new URL(fields.reference); } catch { throw new HttpError(400, 'Evidence link must be an HTTPS URL.'); }
      if (url.protocol !== 'https:' || url.username || url.password) throw new HttpError(400, 'Evidence link must be an HTTPS URL without credentials.');
    }
    if (status === 'confirmed') {
      for (const key of ['firmware','appVersion','testedOn','osVersion','requested','readback','observed','steps']) {
        if (!fields[key] || /^(unknown|not recorded|n\/a|none)$/i.test(fields[key])) throw new HttpError(400, `Confirmed working requires ${key}.`);
      }
    }
    const id = `owner-test-${randomUUID()}`;
    registry.evidence[id] = {
      title: `${model.name}: ${registry.features[feature]} on ${platform}`,
      kind: status === 'confirmed' ? 'hardware confirmation' : status === 'reported' ? 'owner observation' : 'owner review',
      url: `admin-tests.md#${id}`, detail: [note, ...Object.entries(fields).filter(([,v]) => v).map(([k,v]) => `${k}: ${v}`)].join('\n'),
      models:[model.id], platforms:[platform], features:[feature], firmware: fields.firmware ? [fields.firmware] : [],
      test:fields, recordedBy:ownerId, recordedOn:now.toISOString(), result:status,
    };
    model.platforms ||= {}; model.platforms[platform] ||= {};
    model.platforms[platform][feature] = {status, note, evidence:[id]};
  }
  return registry;
}
const md = value => String(value).replaceAll('&','&amp;').replaceAll('<','&lt;').replaceAll('>','&gt;').replaceAll('|','\\|').replaceAll('\n','<br>');
export function testJournal(registry) {
  return '# Owner test records\n\nGenerated by the authenticated owner admin. Each result applies only to its stated setup. Historical records remain when a newer result replaces a status.\n\n' + Object.entries(registry.evidence).filter(([id]) => id.startsWith('owner-test-')).map(([id,r]) => `## ${id}\n\n**${md(r.title)}**\n\nResult: ${md(r.result)}. Recorded: ${md(r.recordedOn)}.\n\n${md(r.detail)}\n`).join('\n');
}
